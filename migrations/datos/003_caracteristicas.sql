-- datos/003_caracteristicas.sql
-- Las caracteristicas: su definicion, cuales ofrece cada categoria y el valor
-- que les da cada uno de los 50 productos y sus 92 variantes.
--
-- Los id empiezan en 1 y cuentan seguido. Estas seis tablas son de este
-- archivo y de ningun otro, asi que no hay bloques que repartir con nadie.
--
-- El id va escrito a mano igual. Sin el, la segunda corrida no chocaria
-- contra nada y duplicaria todo en silencio: estas tablas no tienen ninguna
-- otra llave que lo impida.
--
-- Las definiciones salen de las dos tablas de
-- backend/elementos Generales/Elementos Documentales/productos_subproductos.md,
-- normalizadas a nombre + tipo + unidad. Lo que ahi es un objeto se parte en
-- varias: Dimensiones generales se vuelve Largo, Ancho y Alto, y Duracion de la
-- garantia se queda con el numero mientras la unidad (meses) vive en la
-- definicion. Asi el valor se puede comparar como numero.
--
-- Hay definiciones que ninguna categoria ofrece todavia, las de alimentos
-- (Calorias, Ingredientes). Estan porque el .md las lista y son parte del
-- catalogo de la aplicacion; el dia que exista una categoria de alimentos ya
-- tienen su fila.
--
-- Todo inserta con ON CONFLICT DO NOTHING y con id escrito a mano, para que la
-- segunda corrida choque contra la llave primaria y no duplique.


